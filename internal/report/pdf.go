func pdfHeading(pdf *fpdf.Fpdf, text string) {
	pdf.SetFont("Helvetica", "B", 13)
	pdf.MultiCell(pdfContentWidth, 7, pdfText(text), "", "L", false)
	pdf.Ln(1)
}

func pdfSubHeading(pdf *fpdf.Fpdf, text string) {
	pdf.SetFont("Helvetica", "B", 10)
	pdf.MultiCell(pdfContentWidth, 5.5, pdfText(text), "", "L", false)
	pdf.Ln(0.5)
}

func writePDFKVTable(pdf *fpdf.Fpdf, rows [][2]string) {
	pdf.SetFont("Helvetica", "", 9)
	labelW := 75.0
	valueW := pdfContentWidth - labelW
	for _, row := range rows {
		pdf.CellFormat(labelW, 5.5, pdfText(row[0]), "", 0, "L", false, 0, "")
		pdf.CellFormat(valueW, 5.5, pdfText(row[1]), "", 1, "L", false, 0, "")
	}
}

func writePDFTableHeader(pdf *fpdf.Fpdf, headers []string, widths []float64) {
	pdf.SetFont("Helvetica", "B", 8)
	pdf.SetFillColor(225, 225, 225)
	for i, h := range headers {
		align := "L"
		if i > 0 {
			align = "R"
		}
		pdf.CellFormat(widths[i], 5, pdfText(h), "B", 0, align, true, 0, "")
	}
	pdf.Ln(-1)
}

func writePDFTableRow(pdf *fpdf.Fpdf, cells []string, widths []float64, aligns []string) {
	for i, c := range cells {
		align := "L"
		if i < len(aligns) {
			align = aligns[i]
		}
		pdf.CellFormat(widths[i], 4.5, pdfText(c), "", 0, align, false, 0, "")
	}
	pdf.Ln(-1)
}

func formatFloatHuman(v float64) string {
	switch {
	case v == 0:
		return "0"
	case v < 1:
		return fmt.Sprintf("%.4f", v)
	case v < 1000:
		return fmt.Sprintf("%.2f", v)
	default:
		return commaInt(int64(v))
	}
}

func formatBytes(v uint64) string {
	if v == 0 {
		return "0 B"
	}
	const unit = 1024
	if v < unit {
		return fmt.Sprintf("%d B", v)
	}
	div, exp := uint64(unit), 0
	for n := v / unit; n >= unit; n /= unit {
		div *= unit
		exp++
	}
	suffix := []string{"KiB", "MiB", "GiB", "TiB", "PiB"}[exp]
	return fmt.Sprintf("%.2f %s", float64(v)/float64(div), suffix)
}

func commaInt(v int64) string {
	neg := v < 0
	if neg {
		v = -v
	}
	s := fmt.Sprintf("%d", v)
	n := len(s)
	if n <= 3 {
		if neg {
			return "-" + s
		}
		return s
	}
	var out strings.Builder
	if neg {
		out.WriteByte('-')
	}
	first := n % 3
	if first > 0 {
		out.WriteString(s[:first])
		if n > first {
			out.WriteByte(',')
		}
	}
	for i := first; i < n; i += 3 {
		out.WriteString(s[i : i+3])
		if i+3 < n {
			out.WriteByte(',')
		}
	}
	return out.String()
}

func truncate(s string, max int) string {
	if len(s) <= max {
		return s
	}
	if max <= 3 {
		return s[:max]
	}
	return s[:max-1] + "~"
}

// pdfText sanitizes for the Latin-1 (Windows-1252) core fonts that fpdf ships
// without a TTF — multi-byte runes are replaced with ASCII equivalents or "?".
func pdfText(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		switch {
		case r == '…':
			b.WriteString("...")
		case r == '→':
			b.WriteString("->")
		case r == '—':
			b.WriteString(" - ")
		case r == '–':
			b.WriteByte('-')
		case r == '•':
			b.WriteByte('*')
		case r == '·':
			b.WriteByte('.')
		case r == ' ':
			b.WriteByte(' ')
		case r == '\n' || r == '\t':
			b.WriteRune(r)
		case r >= 0x20 && r < 0x100:
			b.WriteRune(r)
		default:
			b.WriteByte('?')
		}
	}
	return b.String()
}
