const (
	pdfMargin       = 12.0
	pdfPageWidth    = 210.0 // A4 portrait, mm
	pdfContentWidth = pdfPageWidth - 2*pdfMargin
	pdfTopRows      = 25
)

// WritePDFReport writes a printable summary alongside the JSON/CSV/YAML outputs.
// titlePrefix (typically the sanitized team name) appears in headers; empty omits it.
func WritePDFReport(path string, r *Report, byMetric []UnusedByMetricRow, plan OTELProcessorPlan, titlePrefix string) error {
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(pdfMargin, pdfMargin, pdfMargin)
	pdf.SetAutoPageBreak(true, pdfMargin)

	pdf.SetHeaderFunc(func() {
		pdf.SetFont("Helvetica", "I", 8)
		pdf.SetTextColor(120, 120, 120)
		header := "coralogix-unused-metrics-finder"
		if titlePrefix != "" {
			header += " - " + titlePrefix
		}
		pdf.CellFormat(pdfContentWidth, 6, pdfText(header), "", 1, "R", false, 0, "")
		pdf.SetTextColor(0, 0, 0)
	})
	pdf.SetFooterFunc(func() {
		pdf.SetY(-12)
		pdf.SetFont("Helvetica", "I", 8)
		pdf.SetTextColor(120, 120, 120)
		pdf.CellFormat(pdfContentWidth, 6, fmt.Sprintf("Page %d", pdf.PageNo()), "", 0, "C", false, 0, "")
		pdf.SetTextColor(0, 0, 0)
	})
	pdf.AddPage()

	writePDFTitle(pdf, titlePrefix)
	writePDFScanSettings(pdf, r)
	writePDFHeadline(pdf, r, byMetric, plan)
	writePDFTopUnused(pdf, byMetric)
	writePDFOTELPlan(pdf, plan)
	writePDFOTELHowTo(pdf)

	return pdf.OutputFileAndClose(path)
}

func writePDFTitle(pdf *fpdf.Fpdf, titlePrefix string) {
	pdf.SetFont("Helvetica", "B", 18)
	title := "Coralogix Unused Metrics Report"
	if titlePrefix != "" {
		title = titlePrefix + " - " + title
	}
	pdf.MultiCell(pdfContentWidth, 9, pdfText(title), "", "L", false)

	pdf.SetFont("Helvetica", "", 9)
	pdf.SetTextColor(110, 110, 110)
	pdf.MultiCell(pdfContentWidth, 5, pdfText(
		"Generated by coralogix-unused-metrics-finder. Findings reflect the time window in 'Scan settings' below; "+
			"re-run before acting on production. Stripping labels changes metric identity - validate in staging first."),
		"", "L", false)
	pdf.SetTextColor(0, 0, 0)
	pdf.Ln(3)
}

func writePDFScanSettings(pdf *fpdf.Fpdf, r *Report) {
	pdfHeading(pdf, "Scan settings")

	rows := [][2]string{
		{"API host", r.Meta.APIHost},
		{"Dashboards scanned", fmt.Sprintf("%d", r.Meta.DashboardsScanned)},
		{"Alerts scanned", fmt.Sprintf("%d", r.Meta.AlertsScanned)},
		{"SLOs scanned", fmt.Sprintf("%d", r.Meta.SLOsScanned)},
		{"Series lookback", fmt.Sprintf("%d s", r.Meta.SeriesLookbackSeconds)},
		{"Per-metric series limit", fmt.Sprintf("%d", r.Meta.SeriesLimitPerMetric)},
	}
	switch {
	case r.Meta.UsageBillingCalendarMonths > 0:
		rows = append(rows, [2]string{"Billing window", fmt.Sprintf("last %d complete UTC calendar month(s)", r.Meta.UsageBillingCalendarMonths)})
	case r.Meta.UsageLookbackDays > 0:
		rows = append(rows, [2]string{"Billing window", fmt.Sprintf("rolling %d UTC day(s)", r.Meta.UsageLookbackDays)})
	default:
		rows = append(rows, [2]string{"Billing window", "not collected (run with --billing for cost figures)"})
	}
	if r.Meta.UsageBillingUTCStartDate != "" || r.Meta.UsageBillingUTCEndDate != "" {
		rows = append(rows, [2]string{"Billing dates (UTC)", fmt.Sprintf("%s -> %s", r.Meta.UsageBillingUTCStartDate, r.Meta.UsageBillingUTCEndDate)})
	}
	if r.Meta.BillingMetricLookupsAttempted > 0 {
		coverage := fmt.Sprintf("%.0f%% (%d of %d metric lookups succeeded)",
			r.BillingCoverage()*100, r.Meta.BillingMetricLookupsSucceeded, r.Meta.BillingMetricLookupsAttempted)
		switch {
		case r.Meta.BillingPartialAccepted && r.BillingCoverage() < BillingCoverageThreshold:
			coverage += " - partial data accepted via --billing-allow-partial; cost figures understate the total"
		case !r.BillingCoverageSufficient():
			coverage += fmt.Sprintf(" - below the %.0f%% needed to report cost", BillingCoverageThreshold*100)
		}
		rows = append(rows, [2]string{"Billing coverage", coverage})
	}
	if r.Meta.MetricsTruncatedAtSeriesLimit > 0 {
		rows = append(rows, [2]string{"Metrics hit per-metric series cap", fmt.Sprintf("%d (catalog possibly incomplete)", r.Meta.MetricsTruncatedAtSeriesLimit)})
	}
	if r.Meta.SeriesFetchFailuresCount > 0 {
		rows = append(rows, [2]string{"Metrics skipped (series fetch failed)", fmt.Sprintf("%d (usage status unknown)", r.Meta.SeriesFetchFailuresCount)})
		if b := SeriesFetchFailureBreakdown(r.SeriesFetchFailures); b != "" {
			rows = append(rows, [2]string{"  failure categories", b})
		}
	}
	if r.Meta.CoralogixInternalMetricNamesSkipped > 0 {
		rows = append(rows, [2]string{"cx_* metrics skipped", fmt.Sprintf("%d", r.Meta.CoralogixInternalMetricNamesSkipped)})
	}
	writePDFKVTable(pdf, rows)

	if len(r.Warnings) > 0 {
		pdf.Ln(2)
		pdfSubHeading(pdf, "Scan warnings")
		pdf.SetFont("Helvetica", "", 9)
		for _, w := range r.Warnings {
			pdf.MultiCell(pdfContentWidth, 5, pdfText("* "+w), "", "L", false)
		}
	}

	if len(r.SeriesFetchFailures) > 0 {
		pdf.Ln(2)
		pdfSubHeading(pdf, fmt.Sprintf("Metrics excluded from analysis (%d)", len(r.SeriesFetchFailures)))
		pdf.SetFont("Helvetica", "", 9)
		pdf.MultiCell(pdfContentWidth, 5, pdfText(
			"The series catalog for these metric names could not be retrieved - Coralogix refused the query "+
				"(server series-analysis cap), answered with a server error, or it timed out. Typically these "+
				"are the highest-cardinality metrics in the account. They are not in the used/unused "+
				"classification or the OTEL fragment - their usage is unknown, not confirmed unused. Re-run with "+
				"a shorter --series-lookback-hours window, or a larger --timeout-sec for the timed-out ones."),
			"", "L", false)
		limit := pdfTopRows
		if limit > len(r.SeriesFetchFailures) {
			limit = len(r.SeriesFetchFailures)
		}
		pdf.SetFont("Courier", "", 8)
		for _, f := range r.SeriesFetchFailures[:limit] {
			line := "  - " + f.MetricName
			if f.Category != "" {
				line += "  (" + f.Category + ")"
			}
			pdf.MultiCell(pdfContentWidth, 4, pdfText(line), "", "L", false)
		}
		if remaining := len(r.SeriesFetchFailures) - limit; remaining > 0 {
			pdf.SetFont("Helvetica", "I", 8)
			pdf.SetTextColor(110, 110, 110)
			pdf.MultiCell(pdfContentWidth, 4.5, pdfText(
				fmt.Sprintf("  ... %d more - see series_fetch_failures in metric_usage_summary.json.", remaining)),
				"", "L", false)
			pdf.SetTextColor(0, 0, 0)
		}
	}
	pdf.Ln(2)
}

// costCell renders a cost figure, or says why there is none. Without this, a scan with no
// billing data prints "0" for every cost and saving, which reads as a measurement of zero cost
// rather than an absence of data — the worst possible confusion in a customer-facing report.
func costCell(r *Report, formatted string) string {
	if r.BillingCostReportable() {
		return formatted
	}
	if !r.HasBillingData() {
		if r.BillingRequested() {
			return "unavailable - billing lookup returned no data"
		}
		return "not collected - run with --billing"
	}
	return fmt.Sprintf("withheld - billing covered only %.0f%% of metrics (need %.0f%%)",
		r.BillingCoverage()*100, BillingCoverageThreshold*100)
}

func writePDFHeadline(pdf *fpdf.Fpdf, r *Report, byMetric []UnusedByMetricRow, plan OTELProcessorPlan) {
	pdfHeading(pdf, "Headline numbers")

	dropNames := make(map[string]struct{}, len(plan.DropMetricNames))
	for _, n := range plan.DropMetricNames {
		dropNames[n] = struct{}{}
	}

	var (
		dropSeriesCount int
		dropUnitUsage   float64
		dropBytes       uint64
		totalUnitUsage  float64
		totalBytes      uint64
		totalSamples    uint64
	)
	for _, row := range byMetric {
		totalUnitUsage += row.UnitUsageSum
		totalBytes += row.BytesVolumeSum
		totalSamples += row.SampleCountSum
		if _, drop := dropNames[row.MetricName]; drop {
			dropSeriesCount += row.UnusedSeriesCount
			dropUnitUsage += row.UnitUsageSum
			dropBytes += row.BytesVolumeSum
		}
	}
	stripMetricNames := make(map[string]struct{})
	for _, s := range plan.StripStatements {
		stripMetricNames[s.MetricName] = struct{}{}
	}

	totalCatalog := r.Meta.DistinctSeriesInCatalog
	unusedTotal := len(r.UnusedSeriesInCatalog)
	unusedPct := 0.0
	if totalCatalog > 0 {
		unusedPct = 100.0 * float64(unusedTotal) / float64(totalCatalog)
	}

	rows := [][2]string{
		{"Distinct catalog series", commaInt(int64(totalCatalog))},
		{"Used series", commaInt(int64(len(r.UsedSeriesInCatalog)))},
		{"Unused series", fmt.Sprintf("%s (%.1f%% of catalog)", commaInt(int64(unusedTotal)), unusedPct)},
		{"Unused series with CX billing data", costCell(r, fmt.Sprintf("%s of %s", commaInt(int64(r.Meta.UnusedSeriesWithBilling)), commaInt(int64(r.Meta.SeriesWithBillingData))))},
		{"Attributed unit_usage (unused, in window)", costCell(r, formatFloatHuman(totalUnitUsage))},
		{"Attributed bytes_volume (unused, in window)", costCell(r, formatBytes(totalBytes))},
		{"Attributed sample_count (unused, in window)", costCell(r, commaInt(int64(totalSamples)))},
	}
	writePDFKVTable(pdf, rows)
	pdf.Ln(2)

	pdfSubHeading(pdf, "What the OTEL fragment would change")
	rows = [][2]string{
		{"Metrics dropped wholesale", fmt.Sprintf("%d metric name(s), %s series", len(plan.DropMetricNames), commaInt(int64(dropSeriesCount)))},
		{"Estimated unit_usage avoided by drops", costCell(r, formatFloatHuman(dropUnitUsage))},
		{"Estimated bytes_volume avoided by drops", costCell(r, formatBytes(dropBytes))},
		{"Metrics with label keys stripped", fmt.Sprintf("%d metric(s), %d delete_key statement(s)", len(stripMetricNames), len(plan.StripStatements))},
	}
	writePDFKVTable(pdf, rows)
	pdf.SetFont("Helvetica", "I", 8)
	pdf.SetTextColor(110, 110, 110)
	pdf.MultiCell(pdfContentWidth, 4.5, pdfText(
		"Drop savings are the sum of attributed unit_usage and bytes_volume on series for fully-unused metric names "+
			"over the billing window above. Label-strip savings depend on cardinality after the strip and aren't "+
			"summed here - inspect per-metric figures in metric_usage_unused_by_metric.csv."),
		"", "L", false)
	pdf.SetTextColor(0, 0, 0)
	pdf.Ln(2)
}

func writePDFTopUnused(pdf *fpdf.Fpdf, byMetric []UnusedByMetricRow) {
	if len(byMetric) == 0 {
		return
	}
	pdfHeading(pdf, fmt.Sprintf("Top unused metrics by attributed unit_usage (max %d)", pdfTopRows))

	limit := pdfTopRows
	if limit > len(byMetric) {
		limit = len(byMetric)
	}

	headers := []string{"metric_name", "unit_usage_sum", "unused_series", "with_billing", "bytes_volume_sum"}
	widths := []float64{90, 28, 22, 22, 24}
	aligns := []string{"L", "R", "R", "R", "R"}

	writePDFTableHeader(pdf, headers, widths)
	pdf.SetFont("Helvetica", "", 8)
	for _, row := range byMetric[:limit] {
		cells := []string{
			truncate(row.MetricName, 60),
			formatFloatHuman(row.UnitUsageSum),
			commaInt(int64(row.UnusedSeriesCount)),
			commaInt(int64(row.UnusedSeriesWithBillingCount)),
			formatBytes(row.BytesVolumeSum),
		}
		writePDFTableRow(pdf, cells, widths, aligns)
	}
	if len(byMetric) > limit {
		pdf.Ln(1)
		pdf.SetFont("Helvetica", "I", 8)
		pdf.SetTextColor(110, 110, 110)
		pdf.MultiCell(pdfContentWidth, 4.5, pdfText(
			fmt.Sprintf("Showing %d of %d unused metric names - see metric_usage_unused_by_metric.csv for the full list.",
				limit, len(byMetric))),
			"", "L", false)
		pdf.SetTextColor(0, 0, 0)
	}
	pdf.Ln(2)
}

func writePDFOTELPlan(pdf *fpdf.Fpdf, plan OTELProcessorPlan) {
	pdf.AddPage()
	pdfHeading(pdf, "OTEL processor plan")

	if len(plan.DropMetricNames) == 0 && len(plan.StripStatements) == 0 {
		pdf.SetFont("Helvetica", "", 10)
		pdf.MultiCell(pdfContentWidth, 5, pdfText(
			"No metrics qualify for dropping or label-stripping under the current scan settings. "+
				"The generated YAML contains 'processors: {}' and adds nothing to your Collector config."),
			"", "L", false)
		return
	}

	if len(plan.DropMetricNames) > 0 {
		pdfSubHeading(pdf, fmt.Sprintf("metrics_usage_drop_unused_metrics - %d metric name(s)", len(plan.DropMetricNames)))
		pdf.SetFont("Helvetica", "", 9)
		pdf.MultiCell(pdfContentWidth, 5, pdfText(
			"Every catalog series for these metric names was unused in the scanned dashboards, alerts, and SLOs. "+
				"The filter processor drops them at the Collector before they reach Coralogix."),
			"", "L", false)
		showDrops := plan.DropMetricNames
		if len(showDrops) > pdfTopRows {
			showDrops = showDrops[:pdfTopRows]
		}
		pdf.SetFont("Courier", "", 8)
		for _, n := range showDrops {
			pdf.MultiCell(pdfContentWidth, 4, pdfText("  - "+n), "", "L", false)
		}
		if remaining := len(plan.DropMetricNames) - len(showDrops); remaining > 0 {
			pdf.SetFont("Helvetica", "I", 8)
			pdf.SetTextColor(110, 110, 110)
			pdf.MultiCell(pdfContentWidth, 4.5, pdfText(
				fmt.Sprintf("  ... %d more - see metric_usage_otel_processors.yaml for the full list.", remaining)),
				"", "L", false)
			pdf.SetTextColor(0, 0, 0)
		}
		pdf.Ln(2)
	}

	if len(plan.StripStatements) > 0 {
		stripsByMetric := make(map[string][]string)
		var metricOrder []string
		for _, s := range plan.StripStatements {
			if _, ok := stripsByMetric[s.MetricName]; !ok {
				metricOrder = append(metricOrder, s.MetricName)
			}
			stripsByMetric[s.MetricName] = append(stripsByMetric[s.MetricName], s.LabelKey)
		}
		sort.Strings(metricOrder)

		pdfSubHeading(pdf, fmt.Sprintf("metrics_usage_strip_unused_only_labels - %d metric(s), %d statement(s)",
			len(metricOrder), len(plan.StripStatements)))
		pdf.SetFont("Helvetica", "", 9)
		pdf.MultiCell(pdfContentWidth, 5, pdfText(
			"For metric names that still have some used series, these label keys appear only on unused series. "+
				"The transform processor deletes them at the Collector. The metric continues to be ingested with "+
				"reduced label cardinality - which changes its identity, so confirm queries still match in staging."),
			"", "L", false)

		limit := pdfTopRows
		if limit > len(metricOrder) {
			limit = len(metricOrder)
		}
		pdf.SetFont("Courier", "", 8)
		for _, mn := range metricOrder[:limit] {
			keys := stripsByMetric[mn]
			sort.Strings(keys)
			pdf.MultiCell(pdfContentWidth, 4,
				pdfText(fmt.Sprintf("  %s -> strip [%s]", mn, strings.Join(keys, ", "))),
				"", "L", false)
		}
		if remaining := len(metricOrder) - limit; remaining > 0 {
			pdf.SetFont("Helvetica", "I", 8)
			pdf.SetTextColor(110, 110, 110)
			pdf.MultiCell(pdfContentWidth, 4.5, pdfText(
				fmt.Sprintf("  ... %d more metric(s) - see metric_usage_otel_processors.yaml for the full list.", remaining)),
				"", "L", false)
			pdf.SetTextColor(0, 0, 0)
		}
	}
	pdf.Ln(2)
}

